
// Exercise 01: Create a variable x with a value of 7 and a variable y with a value of 3. Perform all the arithmetic operations and log the results.


let x = 7;
let y = 3;

console.log(x + y); // 10
console.log(x - y); // 4
console.log(x * y); // 21
console.log(x / y); // 2.333...
console.log(x % y); // 1
console.log(x ** y); // 343
console.log(x++); // 7 (then x = 8)
console.log(y++); // 3 (then y = 4)
console.log(x--); // 8 (then x = 7)
console.log(y--); // 4 (then y = 3)
